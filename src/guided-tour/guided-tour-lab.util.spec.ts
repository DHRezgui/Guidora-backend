import { ForbiddenException } from '@nestjs/common';
import {
  assertDeveloperLabTourUpdateAllowed,
  buildContextualPublishDedupeKey,
  buildContextualSandboxPublishDedupeKey,
  buildSdkLabPublishDedupeKey,
  isContextualAutogeneratedTour,
  isDeveloperOnlyAutogenTour,
  isSdkLabPublishScopedByCreator,
  isSdkLabPublishedTour,
  isSdkLabTargetPath,
  isSdkLabTemplateTour,
  isLikelyManualContextualTourDerivative,
  isSdkLabTourOwnedBy,
  participatesInContextualPublishDedupe,
} from './guided-tour-lab.util';
import { TourEnvironment, TourSandboxStatus } from './entities/guided-tour.entity';

describe('isContextualAutogeneratedTour', () => {
  it('returns true for contextual-engine metadata on any path', () => {
    expect(
      isContextualAutogeneratedTour({
        targetUrl: '/app/home',
        triggerConditions: { source: 'contextual-engine' },
      }),
    ).toBe(true);
  });
});

describe('isDeveloperOnlyAutogenTour', () => {
  it('returns true for legacy developer autogen in production', () => {
    expect(
      isDeveloperOnlyAutogenTour({
        targetUrl: '/app/home',
        environment: TourEnvironment.PRODUCTION,
        sandboxStatus: null,
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: { publishedByRole: 'DEVELOPER' },
        },
      }),
    ).toBe(true);
  });

  it('returns false for admin-published contextual tours', () => {
    expect(
      isDeveloperOnlyAutogenTour({
        targetUrl: '/app/home',
        environment: TourEnvironment.PRODUCTION,
        sandboxStatus: null,
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: { publishedByRole: 'ADMIN' },
        },
      }),
    ).toBe(false);
  });

  it('returns false for approved sandbox promotions', () => {
    expect(
      isDeveloperOnlyAutogenTour({
        targetUrl: '/app/home',
        environment: TourEnvironment.PRODUCTION,
        sandboxStatus: TourSandboxStatus.APPROVED,
        triggerConditions: { source: 'contextual-engine' },
      }),
    ).toBe(false);
  });
});

describe('isSdkLabPublishedTour', () => {
  it('returns true for contextual engine tours on sdk-tests paths', () => {
    expect(
      isSdkLabPublishedTour({
        targetUrl: '/dashboard/sdk-tests/simple',
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: { scenario: 'simple', flowSignature: 'sig-1' },
        },
      }),
    ).toBe(true);
  });

  it('returns false for manual tours outside sdk-tests', () => {
    expect(
      isSdkLabPublishedTour({
        targetUrl: '/dashboard/transfers',
        triggerConditions: { minTimeOnPage: 30 },
      }),
    ).toBe(false);
  });

  it('returns false for sdk-tests URL without contextual metadata', () => {
    expect(
      isSdkLabPublishedTour({
        targetUrl: '/dashboard/sdk-tests/simple',
        triggerConditions: {},
      }),
    ).toBe(false);
  });
});

describe('contextual publish dedupe participation', () => {
  const canonicalTour = {
    name: 'Parcours SDK',
    triggerConditions: {
      source: 'contextual-engine',
      contextualEngine: {
        source: 'contextual-engine',
        canonicalPublishInstance: true,
        intent: 'primary-action',
        flowSignature: 'sig-1',
      },
    },
  };

  it('includes canonical SDK publish instances', () => {
    expect(participatesInContextualPublishDedupe(canonicalTour)).toBe(true);
  });

  it('excludes dashboard concat derivatives', () => {
    expect(
      participatesInContextualPublishDedupe({
        name: 'Concat - A + B',
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: {
            source: 'dashboard-concat',
            intent: 'primary-action',
            flowSignature: 'sig-1',
          },
        },
      }),
    ).toBe(false);
  });

  it('excludes duplicate copies by name and fork metadata', () => {
    expect(
      participatesInContextualPublishDedupe({
        name: 'Parcours d action (copie)',
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: {
            intent: 'primary-action',
            flowSignature: 'sig-1',
          },
        },
      }),
    ).toBe(false);
    expect(
      isLikelyManualContextualTourDerivative({
        name: 'Parcours SDK',
        triggerConditions: {
          source: 'contextual-engine',
          contextualEngine: {
            source: 'dashboard-fork',
            forkedFromTourIds: ['tour-a'],
            intent: 'primary-action',
            flowSignature: 'sig-1',
          },
        },
      }),
    ).toBe(true);
  });
});

