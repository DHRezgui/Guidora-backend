describe('assertDeveloperLabTourUpdateAllowed', () => {
  it('allows name, description and lab steps', () => {
    expect(() =>
      assertDeveloperLabTourUpdateAllowed({
        name: 'Renamed',
        description: 'Updated',
        steps: [
          {
            title: 'Step',
            content: 'Content',
            targetSelector: '#cta',
            stepTargetUrl: '/dashboard/sdk-tests/simple',
          },
        ],
      }),
    ).not.toThrow();
  });

  it('rejects forbidden tour fields', () => {
    expect(() => assertDeveloperLabTourUpdateAllowed({ targetUrl: '/dashboard/users' })).toThrow(
      ForbiddenException,
    );
    expect(() => assertDeveloperLabTourUpdateAllowed({ isActive: true })).toThrow(ForbiddenException);
    expect(() => assertDeveloperLabTourUpdateAllowed({ priority: 99 })).toThrow(ForbiddenException);
    expect(() =>
      assertDeveloperLabTourUpdateAllowed({ triggerConditions: { source: 'hijack' } }),
    ).toThrow(ForbiddenException);
    expect(() =>
      assertDeveloperLabTourUpdateAllowed({ simulationContext: { pathname: '/evil' } }),
    ).toThrow(ForbiddenException);
    expect(() => assertDeveloperLabTourUpdateAllowed({ replayPolicy: 'always_on_new_version' as never })).toThrow(
      ForbiddenException,
    );
    expect(() => assertDeveloperLabTourUpdateAllowed({ replayAfterDays: 7 })).toThrow(ForbiddenException);
  });

  it('rejects stepTargetUrl outside lab', () => {
    expect(() =>
      assertDeveloperLabTourUpdateAllowed({
        steps: [{ title: 'S', content: 'C', stepTargetUrl: '/dashboard/billing' }],
      }),
    ).toThrow(ForbiddenException);
  });
});
